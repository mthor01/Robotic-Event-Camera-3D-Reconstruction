    base_point = poses[0, :3] * 0.0  # placeholder, overwritten below

    # IMPORTANT: dirs should be "base_point - pose_position" like in the agent
    # base_point is the translation of the base pose used for generation.
    # If you used Option A, you need the base_pose the agent used.
    # Your agent currently hardcodes base_pose in __init__ (recommended: store it).
